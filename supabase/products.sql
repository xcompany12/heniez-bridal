-- Jalankan sekali di Supabase: SQL Editor, lalu Run.
-- Aman dijalankan ulang (tidak menimpa data yang sudah ada).

-- 1. Tabel gaun
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  price bigint not null check (price >= 0),
  silhouette text not null,
  material text not null,
  collection text not null,
  description text not null default '',
  craftsmanship text not null default '',
  colors jsonb not null default '[{"name": "Ivory", "hex": "#F3EBDD"}]'::jsonb,
  images text[] not null default '{}',
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

-- 2. Keamanan: pengunjung hanya boleh MEMBACA gaun yang dipublikasikan.
--    Menulis hanya lewat server admin memakai secret key.
alter table public.products enable row level security;

drop policy if exists "Public can read published gowns" on public.products;
create policy "Public can read published gowns"
  on public.products for select
  to anon, authenticated
  using (is_published);

grant select on table public.products to anon, authenticated;
grant select, insert, update, delete on table public.products to service_role;

-- 3. Tempat penyimpanan foto (publik untuk dibaca, upload hanya lewat server)
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'product-images', 'product-images', true, 5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do nothing;

